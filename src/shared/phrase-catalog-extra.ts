export function extraMetaForPhraseCode(code: string): PhraseCatalogMeta | undefined {
  const entry = PHRASE_CATALOG_EXTRA.find((e) => e.code === code.trim())
  if (!entry?.gradeHint) return undefined
  return {
    gradeHint: entry.gradeHint as PhraseCatalogMeta['gradeHint'],
    area: entry.area ?? 'General'
  }
}

/** Fusiona Excel + ampliación; códigos extra ganan si hay colisión (no debería). */
export function mergePhraseCatalogWithExtra(
  base: PhraseCatalogEntry[]
): PhraseCatalogEntry[] {
  const byCode = new Map<string, PhraseCatalogEntry>()
  for (const e of base) byCode.set(e.code, e)
  for (const e of PHRASE_CATALOG_EXTRA) byCode.set(e.code, e)
  return [...byCode.values()].sort(
    (a, b) => Number(a.code) - Number(b.code) || a.code.localeCompare(b.code)
  )
}
